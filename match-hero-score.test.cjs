const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const src=fs.readFileSync('index.js','utf8');
const start=src.indexOf('function hero(d){'),end=src.indexOf('\nfunction batTable(',start);
assert(start>0&&end>start);
const esc=s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const c=vm.createContext({SPORT:'football',esc,isLive:d=>d.status==='IN_PLAY',enrichStrip:()=>''});
vm.runInContext(src.slice(start,end),c);
let html=c.hero({title:'Moldova at Faroe Islands',status:'IN_PLAY',home:'Faroe Islands',away:'Moldova',fullTime:'1 - 0',homeCrest:null,awayCrest:null});
assert(html.includes('class="bigscore">1 - 0</span>'),'live score must not depend on optional crests');
assert(!html.includes('src=""'),'no empty crest requests');
html=c.hero({title:'Scheduled match',status:'TIMED',fullTime:null});
assert(!html.includes('class="bigscore"'),'do not invent score for unknown fixture');
html=c.hero({title:'A vs B',status:'FINISHED',fullTime:'0 - 0',homeCrest:'https://example.com/a.png'});
assert(html.includes('0 - 0')&&html.includes('https://example.com/a.png'));
c.SPORT='nba';
html=c.hero({title:'A at B',state:'live',bigScore:'12 - 8'});
assert(html.includes('12 - 8'),'other non-cricket sports also keep crest-free scores');
c.SPORT='cricket';
html=c.hero({title:'A vs B',started:true,fullTime:'12 - 8'});
assert(!html.includes('class="bigscore"'),'cricket innings UI unchanged');
console.log('5 match hero crest-independent score cases passed');
